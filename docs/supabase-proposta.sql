-- Proposta para revisão futura. Não executada pela aplicação nem por npm build.
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create type public.app_role as enum (
  'funcionario_autorizado', 'almoxarife', 'coordenador', 'planejamento',
  'diretor', 'proprietario', 'administrador'
);
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  role public.app_role not null,
  active boolean not null default false
);
create table public.contracts (id uuid primary key default gen_random_uuid(), name text not null unique);
create table public.user_contracts (
  user_id uuid references public.profiles(id) on delete cascade,
  contract_id uuid references public.contracts(id) on delete cascade,
  primary key (user_id, contract_id)
);
create table public.materials (
  id bigint generated by default as identity primary key,
  contract_id uuid not null references public.contracts(id),
  code text not null, name text not null, category text not null default '',
  qty numeric not null check (qty >= 0), unit text not null default 'un',
  location text not null default '', brand text not null default '',
  model text not null default '', supplier text not null default '',
  oc text not null default '', nf text not null default '',
  unique (contract_id, code)
);
create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles p where p.id = (select auth.uid()) and p.active and p.role = 'administrador');
$$;
create function private.can_read_contract(target uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.active and (
      p.role in ('diretor', 'proprietario', 'administrador') or exists (
        select 1 from public.user_contracts uc where uc.user_id = p.id and uc.contract_id = target
      )
    )
  );
$$;
revoke all on function private.is_admin() from public;
revoke all on function private.can_read_contract(uuid) from public;
grant execute on function private.is_admin() to authenticated;
grant execute on function private.can_read_contract(uuid) to authenticated;

alter table public.profiles enable row level security;
alter table public.contracts enable row level security;
alter table public.user_contracts enable row level security;
alter table public.materials enable row level security;
revoke all on public.profiles, public.contracts, public.user_contracts, public.materials from anon, authenticated;
grant select on public.profiles, public.contracts, public.user_contracts, public.materials to authenticated;
grant insert, update, delete on public.materials to authenticated;
grant usage on sequence public.materials_id_seq to authenticated;

-- Self profile can be read to communicate inactive status; never self-edited.
create policy profile_read on public.profiles for select to authenticated
  using (id = (select auth.uid()) or private.is_admin());
create policy membership_read on public.user_contracts for select to authenticated
  using ((user_id = (select auth.uid()) and private.can_read_contract(contract_id)) or private.is_admin());
create policy contract_read on public.contracts for select to authenticated
  using (private.can_read_contract(id));
create policy material_read on public.materials for select to authenticated
  using (private.can_read_contract(contract_id));
create policy material_insert on public.materials for insert to authenticated
  with check (private.is_admin());
create policy material_update on public.materials for update to authenticated
  using (private.is_admin()) with check (private.is_admin());
create policy material_delete on public.materials for delete to authenticated
  using (private.is_admin());
-- No browser write grants/policies for profiles or memberships: prevents escalation.
